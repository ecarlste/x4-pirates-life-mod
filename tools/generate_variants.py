#!/usr/bin/env python3
"""Writes the pirate variants listed in profiles/vanilla/variants.xml into the mod.

For each <ship> in the list, from the vanilla files in an unpacked X4 install:
  - assets/units/size_<s|m|l|xl>/macros/ship_apl_<id>_macro.xml: a copy of the vanilla ship macro
    with the rig applied (hull, crew, drag, travel acceleration) and our name; the same model.
  - assets/props/storagemodules/macros/storage_apl_<id>_macro.xml: a copy of its storage macro
    with the cargo multiplier, when the rig changes cargo.
  - index/macros.xml: where X4 finds those macros.
  - libraries/wares.xml: the variant's ware (a copy of the vanilla ship's, priced x the group's price
    multiplier, owned by the group's factions, needing the variant's unlock research to be built)
    and the unlock research ware (hidden from the HQ research tree).
  - t/0001-l044.xml: page 1774110 (between generated markers) with the variants' names
    ("Pirate <vanilla name>") and the unlock research's name and description.
See docs/specs/booty.md (Variants) and docs/research/booty.md (Unlocks in the build menus).

Every generated file is stamped with a hash of the list and of this script. `--check` compares
the committed files with what would be generated: in full when the unpacked game files are there,
and otherwise (as in CI) by checking that every expected file exists and carries the current stamp.

Usage: tools/generate_variants.py [--reference DIR] [--check]
The reference is the unpacked install (tools/unpack-x4.ps1), by default $X4_REFERENCE or
/mnt/e/x4-dev/reference/x4-9.00.
"""
import argparse
import copy
import glob
import hashlib
import os
import re
import sys
import xml.etree.ElementTree as ET

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LIST = os.path.join("profiles", "vanilla", "variants.xml")
DEFAULT_REFERENCE = os.environ.get("X4_REFERENCE", "/mnt/e/x4-dev/reference/x4-9.00")
TEXT_PAGE = 1774110
TEXT_FILE = os.path.join("t", "0001-l044.xml")
TEXT_BEGIN = "<!-- generated variants: begin (tools/generate_variants.py; don't edit by hand) -->"
TEXT_END = "<!-- generated variants: end -->"
STAMP = re.compile(r"Generated by tools/generate_variants\.py, stamp ([0-9a-f]{16})")
SIZES = {"ship_s": "size_s", "ship_m": "size_m", "ship_l": "size_l", "ship_xl": "size_xl"}
DRAG_ATTRS = ("forward", "reverse", "horizontal", "vertical")


def stamp(list_bytes, script_bytes):
    """The first 16 hex digits of the SHA-256 of the list and this script"""
    return hashlib.sha256(list_bytes + b"\0" + script_bytes).hexdigest()[:16]


def header(stamp_value, what):
    return ("<!-- Generated by tools/generate_variants.py, stamp %s, from profiles/vanilla/variants.xml: "
            "%s. Don't edit: change the list and run `make variants`. -->" % (stamp_value, what))


def parse_list(text):
    """The list as (group, rigs, ships): group a dict, rigs {id: {attr: float}}, ships a list of dicts"""
    root = ET.fromstring(text)
    g = root.find("group")
    if g is None:
        raise ValueError("the list has no <group>")
    group = {"id": g.get("id"), "factions": g.get("factions", "").split(), "name": g.get("name", g.get("id"))}
    rigs = {}
    for r in root.findall("rig"):
        rigs[r.get("id")] = {k: float(v) for k, v in r.attrib.items() if k != "id"}
    ships, seen = [], set()
    for s in root.findall("ship"):
        sid = s.get("id")
        if not sid or not re.fullmatch(r"[a-z][a-z0-9_]*", sid):
            raise ValueError("ship id %r: use lowercase letters, digits and underscores" % sid)
        if sid in seen:
            raise ValueError("ship id %r is listed twice" % sid)
        seen.add(sid)
        if s.get("rig") not in rigs:
            raise ValueError("ship %s: unknown rig %r" % (sid, s.get("rig")))
        ships.append({"id": sid, "macro": s.get("macro"), "rig": s.get("rig"), "level": int(s.get("level", "0"))})
    return group, rigs, ships


def scaled(value, factor, integer=False):
    v = float(value) * factor
    return str(int(round(v))) if integer else ("%g" % round(v, 4))


def rig_ship_macro(root, rig, sid, name_ref, storage_name):
    """Applies a rig to a vanilla ship macro (an <macros> element, changed in place)"""
    mac = root.find("macro")
    mac.set("name", "ship_apl_%s_macro" % sid)
    p = mac.find("properties")
    ident = p.find("identification")
    ident.set("name", name_ref)
    for a in ("basename", "variation", "shortvariation"):
        ident.attrib.pop(a, None)
    if "hull" in rig:
        h = p.find("hull")
        h.set("max", scaled(h.get("max"), rig["hull"], integer=True))
    if "crew" in rig and p.find("people") is not None:
        pe = p.find("people")
        old = int(pe.get("capacity"))
        pe.set("capacity", str(max(int(round(old * rig["crew"])), old + 1 if rig["crew"] > 1 else 0)))
    if "drag" in rig:
        d = p.find("physics/drag")
        for a in DRAG_ATTRS:
            if d.get(a) is not None:
                d.set(a, scaled(d.get(a), rig["drag"]))
    if "travelaccel" in rig:
        t = p.find("jerk/forward_travel")
        if t is not None:
            t.set("accel", scaled(t.get("accel"), rig["travelaccel"]))
    if storage_name:
        for c in mac.findall("connections/connection"):
            m = c.find("macro")
            if m is not None and m.get("ref", "").startswith("storage_"):
                m.set("ref", storage_name)
    return root


def rig_storage_macro(root, factor, name):
    mac = root.find("macro")
    mac.set("name", name)
    cg = mac.find("properties/cargo")
    cg.set("max", scaled(cg.get("max"), factor, integer=True))
    return root


def to_text(root, head):
    ET.indent(root, space="  ")
    return '<?xml version="1.0" encoding="utf-8"?>\n' + head + "\n" + ET.tostring(root, encoding="unicode") + "\n"


class Reference:
    """The unpacked install: macro files, ship wares and English texts, base first, then each DLC"""

    def __init__(self, root):
        self.roots = [os.path.join(root, "base")] + sorted(
            d for d in glob.glob(os.path.join(root, "*")) if os.path.basename(d) != "base")
        self.macros = {}
        for r in self.roots:
            for f in glob.glob(os.path.join(r, "assets", "**", "*_macro.xml"), recursive=True):
                self.macros.setdefault(os.path.basename(f)[:-4], f)
        self.wares = {}
        for r in self.roots:
            f = os.path.join(r, "libraries", "wares.xml")
            if os.path.exists(f):
                for w in ET.parse(f).getroot().iter("ware"):
                    c = w.find("component")
                    if c is not None and c.get("ref"):
                        self.wares.setdefault(c.get("ref"), w)
        self.texts = {}
        for r in self.roots:
            f = os.path.join(r, "t", "0001-l044.xml")
            if os.path.exists(f):
                for page in ET.parse(f).getroot().iter("page"):
                    for t in page.iter("t"):
                        self.texts.setdefault((page.get("id"), t.get("id")), t.text or "")

    def text(self, ref, first_only=False):
        """The English text for a {page,id} reference, following references, X4's (comments) removed.
        A text made of several references ("{20101,31201} {20111,5462}": a name and a variation)
        has each resolved; with first_only, only the first (the name without its variation)."""
        for _ in range(5):
            ref = re.sub(r"(?<!\\)\([^)]*\)", "", ref or "")
            refs = re.findall(r"\{\d+,\s*\d+\}", ref or "")
            if not refs:
                break
            if first_only and re.match(r"\s*\{\d+,\s*\d+\}", ref):
                ref = refs[0]
            ref = re.sub(r"\{(\d+),\s*(\d+)\}", lambda m: self.texts.get((m.group(1), m.group(2)), ""), ref)
        return re.sub(r"(?<!\\)\([^)]*\)", "", ref or "").strip()

    def macro(self, name):
        if name not in self.macros:
            raise ValueError("no macro %s in the reference files" % name)
        return ET.parse(self.macros[name]).getroot()


def generate(ref, list_text, list_bytes, script_bytes):
    """{repo-relative path: file text} for everything the list makes"""
    group, rigs, ships = parse_list(list_text)
    st = stamp(list_bytes, script_bytes)
    files, index, wares, texts = {}, [], [], []
    for n, s in enumerate(ships, 1):
        rig = rigs[s["rig"]]
        sid = s["id"]
        root = ref.macro(s["macro"])
        mac = root.find("macro")
        size = SIZES.get(mac.get("class"))
        if not size:
            raise ValueError("%s is not a ship macro (class %s)" % (s["macro"], mac.get("class")))
        ident = mac.find("properties/identification")
        vanilla_name = ref.text(ident.get("basename") or ident.get("name"), first_only=True)
        name_id, research_name_id, research_desc_id = 10 * n + 1, 10 * n + 2, 10 * n + 3
        texts += [(name_id, "Pirate " + vanilla_name),
                  (research_name_id, "%s unlock: standing level %d, bought with booty" % (group["name"], s["level"])),
                  (research_desc_id, "The %s's pirate rig of the %s. Reach standing level %d with the %s, then "
                   "buy the unlock with their booty from a station manager or ship trader at one of their "
                   "wharfs or shipyards." % (group["name"], vanilla_name, s["level"], group["name"]))]
        storage_name = None
        if "cargo" in rig:
            storage_ref = next((c.find("macro").get("ref") for c in mac.findall("connections/connection")
                                if c.find("macro") is not None and c.find("macro").get("ref", "").startswith("storage_")), None)
            if storage_ref:
                storage_name = "storage_apl_%s_macro" % sid
                sroot = rig_storage_macro(ref.macro(storage_ref), rig["cargo"], storage_name)
                path = os.path.join("assets", "props", "storagemodules", "macros", storage_name + ".xml")
                files[path] = to_text(sroot, header(st, "the cargo of the %s variant (%s, x%g)" % (sid, storage_ref, rig["cargo"])))
                index.append((storage_name, path))
        rig_ship_macro(root, rig, sid, "{%d,%d}" % (TEXT_PAGE, name_id), storage_name)
        ship_name = "ship_apl_%s_macro" % sid
        path = os.path.join("assets", "units", size, "macros", ship_name + ".xml")
        files[path] = to_text(root, header(st, "the %s variant of %s, rig %s" % (sid, s["macro"], s["rig"])))
        index.append((ship_name, path))

        vware = ref.wares.get(s["macro"])
        if vware is None:
            raise ValueError("no ware builds %s" % s["macro"])
        research_id = "research_apl_%s" % sid
        w = copy.deepcopy(vware)
        w.set("id", "ship_apl_%s" % sid)
        w.set("name", "{%d,%d}" % (TEXT_PAGE, name_id))
        price = w.find("price")
        for a in ("min", "average", "max"):
            price.set(a, scaled(price.get(a), group_price(group), integer=True))
        for prod in w.findall("production"):
            for old in prod.findall("research"):
                prod.remove(old)
            r = ET.SubElement(prod, "research")
            ET.SubElement(r, "ware", {"ware": research_id})
        w.find("component").set("ref", ship_name)
        for o in w.findall("owner"):
            w.remove(o)
        for f in group["factions"]:
            ET.SubElement(w, "owner", {"faction": f})
        wares.append(w)
        rw = ET.Element("ware", {"id": research_id, "name": "{%d,%d}" % (TEXT_PAGE, research_name_id),
                                 "description": "{%d,%d}" % (TEXT_PAGE, research_desc_id),
                                 "transport": "research", "volume": "1", "tags": "hidden research"})
        ET.SubElement(rw, "price", {"min": "1", "average": "1", "max": "1"})
        prim = ET.SubElement(ET.SubElement(rw, "research", {"time": "1"}), "primary")
        ET.SubElement(prim, "ware", {"ware": "energycells", "amount": "1"})
        wares.append(rw)

    idx = ET.Element("index")
    for name, path in sorted(index):
        ET.SubElement(idx, "entry", {"name": name, "value": "extensions\\apirateslife\\" + path[:-4].replace("/", "\\")})
    files[os.path.join("index", "macros.xml")] = to_text(idx, header(st, "where X4 finds the variant macros"))
    diff = ET.Element("diff")
    add = ET.SubElement(diff, "add", {"sel": "/wares"})
    for w in wares:
        add.append(w)
    files[os.path.join("libraries", "wares.xml")] = to_text(diff, header(
        st, "the variant wares, and the hidden research each needs (tags=\"hidden research\" keeps it out of "
        "the HQ research tree, ui/addons/ego_detailmonitor/menu_research.lua)"))
    page = ['  <page id="%d" title="A Pirate\'s Life" descr="Pirate variants (generated)" voice="no">' % TEXT_PAGE]
    page += ['    <t id="%d">%s</t>' % (i, xml_escape(t)) for i, t in texts]
    page.append("  </page>")
    files[TEXT_FILE] = "\n".join(["  " + TEXT_BEGIN, "  " + header(st, "the variant texts")] + page + ["  " + TEXT_END])
    return files


def group_price(group):
    return float(group.get("price", 1.25))


def xml_escape(s):
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def merge_text_page(current, block):
    """The text file with the generated block put in place of the old one (or before </language>)"""
    pat = re.compile(r"[ \t]*" + re.escape(TEXT_BEGIN) + r".*?" + re.escape(TEXT_END), re.S)
    if pat.search(current):
        return pat.sub(lambda _: block, current, count=1)
    return current.replace("</language>", block + "\n</language>", 1)


def expected_paths(list_text):
    """The files the list makes, known without the game files"""
    group, rigs, ships = parse_list(list_text)
    paths = {os.path.join("index", "macros.xml"), os.path.join("libraries", "wares.xml")}
    for s in ships:
        if "cargo" in rigs[s["rig"]]:
            paths.add(os.path.join("assets", "props", "storagemodules", "macros", "storage_apl_%s_macro.xml" % s["id"]))
    return paths


def generated_on_disk(repo):
    """Repo-relative paths of files carrying a generator stamp (the text file excluded)"""
    found = set()
    for top in ("assets", "index", "libraries"):
        for f in glob.glob(os.path.join(repo, top, "**", "*.xml"), recursive=True):
            with open(f, encoding="utf-8", errors="replace") as fh:
                if STAMP.search(fh.read(400)):
                    found.add(os.path.relpath(f, repo))
    return found


def check_stamps(repo, list_text, current):
    """Problems found without the game files: missing, stale or unstamped generated files"""
    problems = []
    on_disk = generated_on_disk(repo)
    needed = expected_paths(list_text)
    ship_files = {p for p in on_disk if p.startswith(os.path.join("assets", "units"))}
    for p in sorted(needed - on_disk):
        problems.append("missing: %s" % p)
    _, _, ships = parse_list(list_text)
    want_ships = {"ship_apl_%s_macro.xml" % s["id"] for s in ships}
    have_ships = {os.path.basename(p) for p in ship_files}
    for name in sorted(want_ships - have_ships):
        problems.append("missing: ship macro %s" % name)
    for name in sorted(have_ships - want_ships):
        problems.append("left over: ship macro %s (no longer in the list)" % name)
    for p in sorted(on_disk):
        with open(os.path.join(repo, p), encoding="utf-8", errors="replace") as fh:
            m = STAMP.search(fh.read(400))
        if m and m.group(1) != current:
            problems.append("stale: %s (stamp %s, the list and generator make %s)" % (p, m.group(1), current))
    text_path = os.path.join(repo, TEXT_FILE)
    with open(text_path, encoding="utf-8") as fh:
        m = STAMP.search(fh.read())
    if not m or m.group(1) != current:
        problems.append("stale: %s (generated variant texts)" % TEXT_FILE)
    return problems


def main(argv):
    ap = argparse.ArgumentParser(description="Write the pirate variants listed in profiles/vanilla/variants.xml.")
    ap.add_argument("--reference", default=DEFAULT_REFERENCE, help="the unpacked X4 install")
    ap.add_argument("--check", action="store_true", help="compare instead of writing; exit 1 if out of date")
    ap.add_argument("--repo", default=REPO, help=argparse.SUPPRESS)
    args = ap.parse_args(argv)
    list_path = os.path.join(args.repo, LIST)
    with open(list_path, "rb") as fh:
        list_bytes = fh.read()
    with open(os.path.abspath(__file__), "rb") as fh:
        script_bytes = fh.read()
    list_text = list_bytes.decode("utf-8")
    current = stamp(list_bytes, script_bytes)
    have_reference = os.path.isdir(os.path.join(args.reference, "base"))

    if args.check and not have_reference:
        problems = check_stamps(args.repo, list_text, current)
        for p in problems:
            print(p, file=sys.stderr)
        if problems:
            print("Variants out of date: run `make variants` with the unpacked game files and commit.", file=sys.stderr)
            return 1
        print("Variants: stamps match the list (no game files here for a full check)")
        return 0
    if not have_reference:
        print("no unpacked game files at %s (set --reference or X4_REFERENCE)" % args.reference, file=sys.stderr)
        return 1

    files = generate(Reference(args.reference), list_text, list_bytes, script_bytes)
    text_path = os.path.join(args.repo, TEXT_FILE)
    with open(text_path, encoding="utf-8") as fh:
        current_text = fh.read()
    files = dict(files)
    files[TEXT_FILE] = merge_text_page(current_text, files[TEXT_FILE])
    stale = generated_on_disk(args.repo) - set(files)
    if args.check:
        problems = []
        for p, content in sorted(files.items()):
            full = os.path.join(args.repo, p)
            if not os.path.exists(full):
                problems.append("missing: %s" % p)
            else:
                with open(full, encoding="utf-8") as fh:
                    if fh.read() != content:
                        problems.append("differs: %s" % p)
        problems += ["left over: %s" % p for p in sorted(stale)]
        for p in problems:
            print(p, file=sys.stderr)
        if problems:
            print("Variants out of date: run `make variants` and commit.", file=sys.stderr)
            return 1
        print("Variants: up to date (%d files)" % len(files))
        return 0
    for p in sorted(stale):
        os.remove(os.path.join(args.repo, p))
        print("removed %s" % p)
    for p, content in sorted(files.items()):
        full = os.path.join(args.repo, p)
        os.makedirs(os.path.dirname(full), exist_ok=True)
        with open(full, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(content)
    print("wrote %d files (stamp %s)" % (len(files), current))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
