#!/usr/bin/env python3
"""Writes the pirate variants listed in profiles/vanilla/variants.xml into the mod.

For each <ship> in the list, from the vanilla files in an unpacked X4 install:
  - assets/units/size_<s|m|l|xl>/macros/ship_apl_<id>_macro.xml: a copy of the vanilla ship macro
    with the rig applied (hull, crew, drag, travel acceleration) and our name; the same model.
  - assets/props/storagemodules/macros/storage_apl_<id>_macro.xml: a copy of its storage macro
    with the cargo multiplier, when the rig changes cargo.
  - index/macros.xml: where X4 finds those macros.
  - libraries/wares.xml: the variant's ware (a copy of the vanilla ship's, priced x the group's price
    multiplier, owned by the group's factions, needing the variant's unlock research to be built)
    and the unlock research ware (hidden from the HQ research tree).
  - md/apirateslife_variants_vanilla.xml: the MD library (Unlocks) the booty script reads to grant
    each variant's unlock research at its standing level.
  - t/0001-l044.xml: page 1774110 (between generated markers) with the variants' names
    ("Pirate <vanilla name>") and the unlock research's name and description.
Each <equipment> (an engine, shield generator, weapon, turret or missile) gets the same: a rigged copy of
its macro under the vanilla macro's folder (lowercased), its ware and unlock research, and its
name: the vanilla name with "Pirate" for the maker ("Pirate S Combat Engine Mk1"), or, with a fun
name in the list, the fun name for the base name ("S Stripper Mk1"). A weapon also gets a copy of
its bullet macro (assets/fx/weaponfx/macros/bullet_apl_<id>_macro.xml) with the damage rigged, and
gear with a destructible twin (its macro's alias, a ware of its own for L and XL hulls: M turrets and
shields) gets a copy of that too, rigged the same, with its ware under the same unlock; a
missile gets a copy of its effect list (libraries/influenceconfigurations.xml, apl_<id>) with the
durations rigged.
See docs/specs/booty.md (Variants) and docs/research/booty.md (Unlocks in the build menus).

Every run also writes profiles/vanilla/variants.manifest: a stamp (a hash of the list and of this
script) and a hash of each generated file, so a run changes only the files whose content changed,
and the manifest. `--check` compares the committed files with what would be generated: in full when
the unpacked game files are there (and then by the manifest too), and otherwise (as in CI) by the
manifest: its stamp matches the list and script, and every file it lists is there, unchanged, with
none missing or left over.

Usage: tools/generate_variants.py [--reference DIR] [--check]
The reference is the unpacked install (tools/unpack-x4.ps1), by default $X4_REFERENCE or
/mnt/e/x4-dev/reference/x4-9.00.
"""
