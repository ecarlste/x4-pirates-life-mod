LIST = os.path.join("profiles", "vanilla", "variants.xml")
DEFAULT_REFERENCE = os.environ.get("X4_REFERENCE", "/mnt/e/x4-dev/reference/x4-9.00")
TEXT_PAGE = 1774110
TEXT_FILE = os.path.join("t", "0001-l044.xml")
UNLOCKS_FILE = os.path.join("md", "apirateslife_variants_vanilla.xml")
TEXT_BEGIN = "<!-- generated variants: begin (tools/generate_variants.py; don't edit by hand) -->"
TEXT_END = "<!-- generated variants: end -->"
MARKER = "Generated by tools/generate_variants.py from profiles/vanilla/variants.xml"
MANIFEST = os.path.join("profiles", "vanilla", "variants.manifest")
SIZES = {"ship_s": "size_s", "ship_m": "size_m", "ship_l": "size_l", "ship_xl": "size_xl"}
DRAG_ATTRS = ("forward", "reverse", "horizontal", "vertical")


def stamp(list_bytes, script_bytes):
    """The first 16 hex digits of the SHA-256 of the list and this script"""
    return hashlib.sha256(list_bytes + b"\0" + script_bytes).hexdigest()[:16]


def header(what):
    return ("<!-- Generated by tools/generate_variants.py from profiles/vanilla/variants.xml: "
            "%s. Don't edit: change the list and run `make variants`. -->" % what)


def content_hash(text):
    return hashlib.sha256(text.encode("utf-8")).hexdigest()[:16]


def manifest_text(st, files):
    """The manifest: the stamp of the list and generator, then a hash of each generated file (for the
    text file, of its generated block), so a regeneration changes only the files whose content changed"""
    lines = ["# Generated by tools/generate_variants.py from profiles/vanilla/variants.xml: the stamp of the list",
             "# and the generator, and a hash of each file it writes. Don't edit: change the list and run",
             "# `make variants`. `--check` reads this file when the unpacked game files aren't there (as in CI).",
             "stamp %s" % st]
    lines += ["%s  %s" % (content_hash(text), path.replace(os.sep, "/")) for path, text in sorted(files.items())]
    return "\n".join(lines) + "\n"


def read_manifest(repo):
    """(stamp, {repo-relative path: hash}) from the manifest, or (None, {}) when it's missing"""
    path = os.path.join(repo, MANIFEST)
    if not os.path.exists(path):
        return None, {}
    st, hashes = None, {}
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            if line.startswith("stamp "):
                st = line.split()[1]
            else:
                h, rel = line.split(None, 1)
                hashes[rel.replace("/", os.sep)] = h
    return st, hashes


def text_block(text):
    """The generated block of the text file, or None"""
    m = re.search(r"[ \t]*" + re.escape(TEXT_BEGIN) + r".*?" + re.escape(TEXT_END), text, re.S)
    return m.group(0) if m else None


def parse_list(text):
    """The list as (group, rigs, items): group a dict, rigs {id: {attr: float}}, items the <ship> and
    <equipment> entries in list order, as dicts with their kind"""
    root = ET.fromstring(text)
    g = root.find("group")
    if g is None:
        raise ValueError("the list has no <group>")
    group = {"id": g.get("id"), "factions": g.get("factions", "").split(), "name": g.get("name", g.get("id"))}
    rigs = {}
    for r in root.findall("rig"):
        rigs[r.get("id")] = {k: float(v) for k, v in r.attrib.items() if k != "id"}
    items, seen = [], set()
    for s in root:
        if s.tag not in ("ship", "equipment"):
            continue
        sid = s.get("id")
        if not sid or not re.fullmatch(r"[a-z][a-z0-9_]*", sid):
            raise ValueError("%s id %r: use lowercase letters, digits and underscores" % (s.tag, sid))
        if sid in seen:
            raise ValueError("id %r is listed twice" % sid)
        seen.add(sid)
        if s.get("rig") not in rigs:
            raise ValueError("%s %s: unknown rig %r" % (s.tag, sid, s.get("rig")))
        items.append({"kind": s.tag, "id": sid, "macro": s.get("macro"), "rig": s.get("rig"),
                      "level": int(s.get("level", "0")), "name": s.get("name")})
    return group, rigs, items


def macro_name(item):
    """The variant's macro name: ship_apl_<id>_macro, engine_apl_<id>_macro, weapon_apl_<id>_macro..."""
    return "%s_apl_%s_macro" % (item["macro"].split("_")[0], item["id"])


def ware_id(item):
    return macro_name(item)[: -len("_macro")]


def scaled(value, factor, integer=False):
    v = float(value) * factor
    return str(int(round(v))) if integer else ("%g" % round(v, 4))


def rig_ship_macro(root, rig, sid, name_ref, storage_name):
    """Applies a rig to a vanilla ship macro (an <macros> element, changed in place)"""
    mac = root.find("macro")
    mac.set("name", "ship_apl_%s_macro" % sid)
    p = mac.find("properties")
    ident = p.find("identification")
    ident.set("name", name_ref)
    for a in ("basename", "variation", "shortvariation"):
        ident.attrib.pop(a, None)
    if "hull" in rig:
        h = p.find("hull")
        h.set("max", scaled(h.get("max"), rig["hull"], integer=True))
    if "crew" in rig and p.find("people") is not None:
        pe = p.find("people")
        old = int(pe.get("capacity"))
        pe.set("capacity", str(max(int(round(old * rig["crew"])), old + 1 if rig["crew"] > 1 else 0)))
    if "drag" in rig:
        d = p.find("physics/drag")
        for a in DRAG_ATTRS:
            if d.get(a) is not None:
                d.set(a, scaled(d.get(a), rig["drag"]))
    if "travelaccel" in rig:
        t = p.find("jerk/forward_travel")
        if t is not None:
            t.set("accel", scaled(t.get("accel"), rig["travelaccel"]))
    if storage_name:
        for c in mac.findall("connections/connection"):
            m = c.find("macro")
            if m is not None and m.get("ref", "").startswith("storage_"):
                m.set("ref", storage_name)
    return root


def rig_storage_macro(root, factor, name):
    mac = root.find("macro")
    mac.set("name", name)
    cg = mac.find("properties/cargo")
    cg.set("max", scaled(cg.get("max"), factor, integer=True))
    return root


def unlock_name(group, item):
    return "%s unlock: standing level %d" % (group["name"], item["level"])


def unlock_description(group, item, vanilla_name):
    return ("The %s's pirate rig of the %s. Reach standing level %d with the %s, by handing them prizes, "
            "and their wharfs and shipyards sell it to you." % (group["name"], vanilla_name, item["level"], group["name"]))


def unlocks_md(group, items):
    """The MD library the booty script reads to grant each unlock at its level: one
    table[$group, $level, $research, $ware] per variant, in list order"""
    entries = ["table[$group = '%s', $level = %d, $research = ware.research_apl_%s, $ware = ware.%s]"
               % (group["id"], s["level"], s["id"], ware_id(s)) for s in items]
    lines = ['<mdscript name="APiratesLife_VariantsVanilla" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" '
             'xsi:noNamespaceSchemaLocation="md.xsd">',
             "  <cues>",
             "    <!-- The variants' unlocks: the group whose standing unlocks each, at which level -->",
             '    <library name="Unlocks" purpose="run_actions">',
             "      <actions>",
             '        <return value="[' + (",\n          ".join(entries)).replace("\\n", "\n") + ']"/>',
             "      </actions>",
             "    </library>",
             "  </cues>",
             "</mdscript>"]
    return '<?xml version="1.0" encoding="utf-8"?>\n' + header("the variants' unlocks, by group and level") + "\n" + "\n".join(lines) + "\n"


def to_text(root, head):
    ET.indent(root, space="  ")
    return '<?xml version="1.0" encoding="utf-8"?>\n' + head + "\n" + ET.tostring(root, encoding="unicode") + "\n"


class Reference:
    """The unpacked install: macro files, ship wares and English texts, base first, then each DLC"""

    def __init__(self, root):
        self.roots = [os.path.join(root, "base")] + sorted(
            d for d in glob.glob(os.path.join(root, "*")) if os.path.basename(d) != "base")
        self.macros = {}
        for r in self.roots:
            for f in glob.glob(os.path.join(r, "assets", "**", "*_macro.xml"), recursive=True):
                self.macros.setdefault(os.path.basename(f)[:-4], f)
        self.wares = {}
        for r in self.roots:
            f = os.path.join(r, "libraries", "wares.xml")
            if os.path.exists(f):
                for w in ET.parse(f).getroot().iter("ware"):
                    c = w.find("component")
                    if c is not None and c.get("ref"):
                        self.wares.setdefault(c.get("ref"), w)
        self.influences = {}
        for r in self.roots:
            f = os.path.join(r, "libraries", "influenceconfigurations.xml")
            if os.path.exists(f):
                for il in ET.parse(f).getroot().iter("influencelist"):
                    self.influences.setdefault(il.get("id"), il)
        self.texts = {}
        for r in self.roots:
            f = os.path.join(r, "t", "0001-l044.xml")
            if os.path.exists(f):
                for page in ET.parse(f).getroot().iter("page"):
                    for t in page.iter("t"):
                        self.texts.setdefault((page.get("id"), t.get("id")), t.text or "")

    def text(self, ref, first_only=False):
        """The English text for a {page,id} reference, following references, X4's (comments) removed.
        A text made of several references ("{20101,31201} {20111,5462}": a name and a variation)
        has each resolved; with first_only, only the first (the name without its variation)."""
        for _ in range(5):
            ref = re.sub(r"(?<!\\)\([^)]*\)", "", ref or "")
            refs = re.findall(r"\{\d+,\s*\d+\}", ref or "")
            if not refs:
                break
            if first_only and re.match(r"\s*\{\d+,\s*\d+\}", ref):
                ref = refs[0]
            ref = re.sub(r"\{(\d+),\s*(\d+)\}", lambda m: self.texts.get((m.group(1), m.group(2)), ""), ref)
        return re.sub(r"(?<!\\)\([^)]*\)", "", ref or "").strip()

    def macro(self, name):
        if name not in self.macros:
            raise ValueError("no macro %s in the reference files" % name)
        return ET.parse(self.macros[name]).getroot()

    def macro_folder(self, name):
        """The macro's folder relative to its install folder (base or a DLC), lowercased"""
        path = self.macros[name]
        root = next(r for r in self.roots if path.startswith(r + os.sep))
        return os.path.dirname(os.path.relpath(path, root)).lower()

    def equipment_name(self, ident, fun=None):
        """A pirate name for equipment from its identification: vanilla names are references like
        "{maker} {size} {base name} {Mk}". The maker becomes "Pirate"; with a fun name, the maker
        goes and the fun name replaces the base name."""
        raw = self.texts.get(tuple(re.findall(r"\d+", ident.get("name"))[:2]), "")
        raw = re.sub(r"(?<!\\)\([^)]*\)", "", raw)
        base = ident.get("basename", "").replace(" ", "")
        parts, has_maker = [], False
        for token in re.findall(r"\{\d+,\s*\d+\}", raw):
            page = re.findall(r"\d+", token)[0]
            if page == "20202":
                has_maker = True
                if not fun:
                    parts.append("Pirate")
            elif fun and token.replace(" ", "") == base:
                parts.append(fun)
            else:
                parts.append(self.text(token))
        if not fun and not has_maker:
            parts.insert(0, "Pirate")
        return " ".join(p for p in parts if p)


def generate(ref, list_text, list_bytes, script_bytes):
    """{repo-relative path: file text} for everything the list makes"""
    group, rigs, items = parse_list(list_text)
    files, index, wares, texts, influences = {}, [], [], [], []
    for n, s in enumerate(items, 1):
        if s["kind"] == "equipment":
            generate_equipment(ref, group, s, rigs[s["rig"]], n, files, index, wares, texts, influences)
            continue
        rig = rigs[s["rig"]]
        sid = s["id"]
        root = ref.macro(s["macro"])
        mac = root.find("macro")
        size = SIZES.get(mac.get("class"))
        if not size:
            raise ValueError("%s is not a ship macro (class %s)" % (s["macro"], mac.get("class")))
        ident = mac.find("properties/identification")
        vanilla_name = ref.text(ident.get("basename") or ident.get("name"), first_only=True)
        name_id, research_name_id, research_desc_id = 10 * n + 1, 10 * n + 2, 10 * n + 3
        texts += [(name_id, "Pirate " + vanilla_name),
                  (research_name_id, unlock_name(group, s)),
                  (research_desc_id, unlock_description(group, s, vanilla_name))]
        storage_name = None
        if "cargo" in rig:
            storage_ref = next((c.find("macro").get("ref") for c in mac.findall("connections/connection")
                                if c.find("macro") is not None and c.find("macro").get("ref", "").startswith("storage_")), None)
            if storage_ref:
                storage_name = "storage_apl_%s_macro" % sid
                sroot = rig_storage_macro(ref.macro(storage_ref), rig["cargo"], storage_name)
                path = os.path.join("assets", "props", "storagemodules", "macros", storage_name + ".xml")
                files[path] = to_text(sroot, header("the cargo of the %s variant (%s, x%g)" % (sid, storage_ref, rig["cargo"])))
                index.append((storage_name, path))
        rig_ship_macro(root, rig, sid, "{%d,%d}" % (TEXT_PAGE, name_id), storage_name)
        ship_name = "ship_apl_%s_macro" % sid
        path = os.path.join("assets", "units", size, "macros", ship_name + ".xml")
        files[path] = to_text(root, header("the %s variant of %s, rig %s" % (sid, s["macro"], s["rig"])))
        index.append((ship_name, path))

        wares += variant_wares(ref, group, s, n)

    idx = ET.Element("index")
    for name, path in sorted(index):
        ET.SubElement(idx, "entry", {"name": name, "value": "extensions\\apirateslife\\" + path[:-4].replace("/", "\\")})
    files[os.path.join("index", "macros.xml")] = to_text(idx, header("where X4 finds the variant macros"))
    diff = ET.Element("diff")
    add = ET.SubElement(diff, "add", {"sel": "/wares"})
    for w in wares:
        add.append(w)
    files[os.path.join("libraries", "wares.xml")] = to_text(diff, header("the variant wares, and the hidden research each needs (tags=\"hidden research\" keeps it out of "
        "the HQ research tree, ui/addons/ego_detailmonitor/menu_research.lua)"))
    if influences:
        idiff = ET.Element("diff")
        iadd = ET.SubElement(idiff, "add", {"sel": "/influencelistconfigurations"})
        for il in influences:
            iadd.append(il)
        files[os.path.join("libraries", "influenceconfigurations.xml")] = to_text(idiff, header("the effect lists of the pirate missiles"))
    files[UNLOCKS_FILE] = unlocks_md(group, items)
    page = ['  <page id="%d" title="A Pirate\'s Life" descr="Pirate variants (generated)" voice="no">' % TEXT_PAGE]
    page += ['    <t id="%d">%s</t>' % (i, xml_escape(t)) for i, t in texts]
    page.append("  </page>")
    files[TEXT_FILE] = "\n".join(["  " + TEXT_BEGIN, "  " + header("the variant texts")] + page + ["  " + TEXT_END])
    return files


def variant_ware(ref, group, vanilla_macro, new_macro, research_id, n):
    """A copy of the ware built from the vanilla macro, built from the new one: priced x the group's
    multiplier, owned by the group's factions, every production method needing the unlock"""
    vware = ref.wares.get(vanilla_macro)
    if vware is None:
        raise ValueError("no ware is built from %s" % vanilla_macro)
    w = copy.deepcopy(vware)
    w.set("id", new_macro[: -len("_macro")])
    w.set("name", "{%d,%d}" % (TEXT_PAGE, 10 * n + 1))
    price = w.find("price")
    for a in ("min", "average", "max"):
        price.set(a, scaled(price.get(a), group_price(group), integer=True))
    for prod in w.findall("production"):
        for old in prod.findall("research"):
            prod.remove(old)
        r = ET.SubElement(prod, "research")
        ET.SubElement(r, "ware", {"ware": research_id})
    w.find("component").set("ref", new_macro)
    for o in w.findall("owner"):
        w.remove(o)
    for f in group["factions"]:
        ET.SubElement(w, "owner", {"faction": f})
    return w


def variant_wares(ref, group, item, n):
    """The variant's ware (a copy of the vanilla one: priced x the group's multiplier, owned by the
    group's factions, every production method needing the unlock) and its unlock research"""
    research_id = "research_apl_%s" % item["id"]
    w = variant_ware(ref, group, item["macro"], macro_name(item), research_id, n)
    rw = ET.Element("ware", {"id": research_id, "name": "{%d,%d}" % (TEXT_PAGE, 10 * n + 2),
                             "description": "{%d,%d}" % (TEXT_PAGE, 10 * n + 3),
                             "transport": "research", "volume": "1", "tags": "hidden research"})
    ET.SubElement(rw, "price", {"min": "1", "average": "1", "max": "1"})
    prim = ET.SubElement(ET.SubElement(rw, "research", {"time": "1"}), "primary")
    ET.SubElement(prim, "ware", {"ware": "energycells", "amount": "1"})
    return [w, rw]


# Equipment rigs: rig attribute -> (property element, attribute, whole number)
ENGINE_RIG = {"thrust": ("thrust", "forward", False), "reverse": ("thrust", "reverse", False),
              "travelthrust": ("travel", "thrust", False), "boostthrust": ("boost", "thrust", False),
              "boostduration": ("boost", "duration", False), "boostrecharge": ("boost", "recharge", False)}
SHIELD_RIG = {"capacity": ("recharge", "max", True), "rate": ("recharge", "rate", False),
              "delay": ("recharge", "delay", False)}


def apply_rig(props, rig, table):
    for key, (element, attr, integer) in table.items():
        if key in rig:
            e = props.find(element)
            if e is None or e.get(attr) is None:
                raise ValueError("the rig sets %s, but the macro has no %s %s" % (key, element, attr))
            e.set(attr, scaled(e.get(attr), rig[key], integer))


def generate_equipment(ref, group, item, rig, n, files, index, wares, texts, influences):
    root = ref.macro(item["macro"])
    mac = root.find("macro")
    cls = mac.get("class")
    props = mac.find("properties")
    ident = props.find("identification")
    name = ref.equipment_name(ident, item["name"])
    vanilla_name = ref.equipment_name(ident, None).replace("Pirate ", "", 1)
    texts += [(10 * n + 1, name),
              (10 * n + 2, unlock_name(group, item)),
              (10 * n + 3, unlock_description(group, item, vanilla_name))]
    new_name = macro_name(item)
    mac.set("name", new_name)
    ident.set("name", "{%d,%d}" % (TEXT_PAGE, 10 * n + 1))
    ident.set("shortname", "{%d,%d}" % (TEXT_PAGE, 10 * n + 1))
    ident.attrib.pop("basename", None)
    if cls == "engine":
        apply_rig(props, rig, ENGINE_RIG)
    elif cls == "shieldgenerator":
        apply_rig(props, rig, SHIELD_RIG)
    elif cls in ("weapon", "turret"):
        bullet = props.find("bullet")
        bullet_name = "bullet_apl_%s_macro" % item["id"]
        broot = ref.macro(bullet.get("class"))
        bmac = broot.find("macro")
        bmac.set("name", bullet_name)
        dmg = bmac.find("properties/damage")
        hull = float(dmg.get("value", 0))
        shield = float(dmg.get("shield", hull))
        dmg.set("value", scaled(hull, rig.get("hulldamage", 1.0)))
        dmg.set("shield", scaled(shield, rig.get("shielddamage", 1.0)))
        bpath = os.path.join(ref.macro_folder(bullet.get("class")), bullet_name + ".xml")
        files[bpath] = to_text(broot, header("the bullet of the %s variant (%s)" % (item["id"], bullet.get("class"))))
        index.append((bullet_name, bpath))
        bullet.set("class", bullet_name)
    elif cls == "missile":
        m = props.find("missile")
        il = copy.deepcopy(ref.influences[m.get("influencelist")])
        il.set("id", "apl_%s" % item["id"])
        for prof in il.iter("profile"):
            for a in ("duration", "attackduration", "sustainduration", "releaseduration"):
                if prof.get(a) is not None:
                    prof.set(a, scaled(prof.get(a), rig.get("disable", 1.0)))
        influences.append(il)
        m.set("influencelist", "apl_%s" % item["id"])
    else:
        raise ValueError("%s: no rig for equipment of class %s" % (item["macro"], cls))
    if mac.get("alias"):
        # The alias is the gear's destructible twin (M turrets and shields), a ware of its own for the
        # slots where it can be shot off (L and XL hulls): it gets the same rig, name and unlock
        vanilla_alias = mac.get("alias")
        alias_name = new_name[: -len("_macro")] + "_alias_macro"
        aroot = ref.macro(vanilla_alias)
        amac = aroot.find("macro")
        amac.set("name", alias_name)
        aprops = amac.find("properties")
        aident = aprops.find("identification")
        for a in ("name", "shortname"):
            aident.set(a, ident.get(a))
        aident.attrib.pop("basename", None)
        if cls == "engine":
            apply_rig(aprops, rig, ENGINE_RIG)
        elif cls == "shieldgenerator":
            apply_rig(aprops, rig, SHIELD_RIG)
        elif cls in ("weapon", "turret"):
            aprops.find("bullet").set("class", props.find("bullet").get("class"))
        else:
            aprops.find("missile").set("influencelist", props.find("missile").get("influencelist"))
        apath = os.path.join(ref.macro_folder(vanilla_alias), alias_name + ".xml")
        files[apath] = to_text(aroot, header("the destructible twin of the %s variant (%s), rig %s" % (item["id"], vanilla_alias, item["rig"])))
        index.append((alias_name, apath))
        mac.set("alias", alias_name)
        wares.append(variant_ware(ref, group, vanilla_alias, alias_name, "research_apl_%s" % item["id"], n))
    path = os.path.join(ref.macro_folder(item["macro"]), new_name + ".xml")
    files[path] = to_text(root, header("the %s variant of %s, rig %s" % (item["id"], item["macro"], item["rig"])))
    index.append((new_name, path))
    wares += variant_wares(ref, group, item, n)


def group_price(group):
    return float(group.get("price", 1.25))


def xml_escape(s):
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def merge_text_page(current, block):
    """The text file with the generated block put in place of the old one (or before </language>)"""
    pat = re.compile(r"[ \t]*" + re.escape(TEXT_BEGIN) + r".*?" + re.escape(TEXT_END), re.S)
    if pat.search(current):
        return pat.sub(lambda _: block, current, count=1)
    return current.replace("</language>", block + "\n</language>", 1)


def expected_paths(list_text):
    """The files the list makes, known without the game files"""
    group, rigs, items = parse_list(list_text)
    paths = {os.path.join("index", "macros.xml"), os.path.join("libraries", "wares.xml"), UNLOCKS_FILE}
    for s in items:
        if s["kind"] == "ship" and "cargo" in rigs[s["rig"]]:
            paths.add(os.path.join("assets", "props", "storagemodules", "macros", "storage_apl_%s_macro.xml" % s["id"]))
        if s["macro"].startswith("missile_"):
            paths.add(os.path.join("libraries", "influenceconfigurations.xml"))
    return paths


def expected_macros(list_text):
    """The file names of the variant macros the list makes (storage macros aside), known without the game files"""
    _, _, items = parse_list(list_text)
    names = {macro_name(s) + ".xml" for s in items}
    names |= {"bullet_apl_%s_macro.xml" % s["id"] for s in items if s["macro"].startswith(("weapon_", "turret_"))}
    return names


def generated_on_disk(repo):
    """Repo-relative paths of files carrying the generator's header (the text file excluded)"""
    found = set()
    for top in ("assets", "index", "libraries", "md"):
        for f in glob.glob(os.path.join(repo, top, "**", "*.xml"), recursive=True):
            with open(f, encoding="utf-8", errors="replace") as fh:
                if MARKER in fh.read(400):
                    found.add(os.path.relpath(f, repo))
    return found


def check_manifest(repo, list_text, current):
    """Problems found without the game files, from the manifest: the list or generator changed since
    the last run, or generated files missing, changed by hand or left over"""
    st, hashes = read_manifest(repo)
    if st is None:
        return ["missing: %s" % MANIFEST]
    problems = []
    if st != current:
        problems.append("stale: %s (stamp %s, the list and generator make %s)" % (MANIFEST, st, current))
    for p, h in sorted(hashes.items()):
        full = os.path.join(repo, p)
        if not os.path.exists(full):
            problems.append("missing: %s" % p)
            continue
        with open(full, encoding="utf-8") as fh:
            text = fh.read()
        if p == TEXT_FILE:
            text = text_block(text) or ""
        if content_hash(text) != h:
            problems.append("changed by hand: %s (not what the generator wrote)" % p)
    for p in sorted(generated_on_disk(repo) - set(hashes)):
        problems.append("left over: %s (not in %s)" % (p, MANIFEST))
    for p in sorted(expected_paths(list_text) - set(hashes)):
        problems.append("missing: %s" % p)
    macro_files = {p for p in hashes if p.startswith("assets" + os.sep) and "_apl_" in os.path.basename(p)
                   and not os.path.basename(p).startswith("storage_apl_")}
    want = expected_macros(list_text)
    # Gear's destructible twin (_alias) comes with it: the list can't tell which gear has one
    have = {os.path.basename(p).replace("_alias_macro", "_macro") for p in macro_files}
    for name in sorted(want - have):
        problems.append("missing: macro %s" % name)
    for name in sorted(have - want):
        problems.append("left over: macro %s (no longer in the list)" % name)
    names = {os.path.basename(p) for p in macro_files}
    for p in sorted(macro_files):
        if not os.path.exists(os.path.join(repo, p)):
            continue
        alias = ET.parse(os.path.join(repo, p)).getroot().find("macro").get("alias")
        if alias and "_apl_" not in alias:
            problems.append("stale: %s still points at the vanilla twin %s" % (p, alias))
        elif alias and alias + ".xml" not in names:
            problems.append("missing: macro %s (the destructible twin of %s)" % (alias + ".xml", os.path.basename(p)))
    return problems


def main(argv):
    ap = argparse.ArgumentParser(description="Write the pirate variants listed in profiles/vanilla/variants.xml.")
    ap.add_argument("--reference", default=DEFAULT_REFERENCE, help="the unpacked X4 install")
    ap.add_argument("--check", action="store_true", help="compare instead of writing; exit 1 if out of date")
    ap.add_argument("--repo", default=REPO, help=argparse.SUPPRESS)
    args = ap.parse_args(argv)
    list_path = os.path.join(args.repo, LIST)
    with open(list_path, "rb") as fh:
        list_bytes = fh.read()
    with open(os.path.abspath(__file__), "rb") as fh:
        script_bytes = fh.read()
    list_text = list_bytes.decode("utf-8")
    current = stamp(list_bytes, script_bytes)
    have_reference = os.path.isdir(os.path.join(args.reference, "base"))

    if args.check and not have_reference:
        problems = check_manifest(args.repo, list_text, current)
        for p in problems:
            print(p, file=sys.stderr)
        if problems:
            print("Variants out of date: run `make variants` with the unpacked game files and commit.", file=sys.stderr)
            return 1
        print("Variants: the manifest matches the list and the files (no game files here for a full check)")
        return 0
    if not have_reference:
        print("no unpacked game files at %s (set --reference or X4_REFERENCE)" % args.reference, file=sys.stderr)
        return 1

    files = generate(Reference(args.reference), list_text, list_bytes, script_bytes)
    text_path = os.path.join(args.repo, TEXT_FILE)
    with open(text_path, encoding="utf-8") as fh:
        current_text = fh.read()
    manifest = manifest_text(current, files)
    files = dict(files)
    files[TEXT_FILE] = merge_text_page(current_text, files[TEXT_FILE])
    stale = generated_on_disk(args.repo) - set(files)
    if args.check:
        problems = []
        for p, content in sorted(files.items()):
            full = os.path.join(args.repo, p)
            if not os.path.exists(full):
                problems.append("missing: %s" % p)
            else:
                with open(full, encoding="utf-8") as fh:
                    if fh.read() != content:
                        problems.append("differs: %s" % p)
        problems += ["left over: %s" % p for p in sorted(stale)]
        if not problems:
            # The manifest check CI runs, so a local run fails wherever CI would
            problems = check_manifest(args.repo, list_text, current)
        for p in problems:
            print(p, file=sys.stderr)
        if problems:
            print("Variants out of date: run `make variants` and commit.", file=sys.stderr)
            return 1
        print("Variants: up to date (%d files)" % len(files))
        return 0
    for p in sorted(stale):
        os.remove(os.path.join(args.repo, p))
        print("removed %s" % p)
    files[MANIFEST] = manifest
    for p, content in sorted(files.items()):
        full = os.path.join(args.repo, p)
        os.makedirs(os.path.dirname(full), exist_ok=True)
        with open(full, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(content)
    print("wrote %d files and %s (stamp %s)" % (len(files) - 1, MANIFEST, current))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
