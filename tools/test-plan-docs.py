#!/usr/bin/env python3
"""Writes the readable test plan: docs/test-plan/<feature>.md for every feature file in
tests/game/features/, plus docs/test-plan/README.md, an index with the coverage per feature.

The feature files stay the source; these pages are generated from them (and from which tests
exist) so the plan can be read on GitHub at any commit. Each scenario is labelled with how it's
verified: by unit tests, by game tests, by hand (@manual), or by hand until its planned test
exists (@pending). Manual plus pending is the number to drive to zero (docs/PROJECT.md, "Test
plan").

Usage:
  tools/test-plan-docs.py           write the pages (make test-plan)
  tools/test-plan-docs.py --check   exit 1, naming the pages, if any page is out of date (CI)
Paths can be overridden for tests: --features DIR --harness FILE --units DIR --out DIR
"""
import argparse
import glob
import importlib.util
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LEVELS = ("unit", "game", "manual", "pending")
HEADER = "<!-- Generated by tools/test-plan-docs.py from {source}. Don't edit: change the feature file and run make test-plan. -->"


def load_checker():
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "check-test-plan.py")
    spec = importlib.util.spec_from_file_location("check_test_plan", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def feature_info(path):
    """The feature's title, description lines and spec (from a "# Spec: <path>" comment)."""
    title, description, spec, in_feature = os.path.basename(path), [], None, False
    with open(path, encoding="utf-8") as f:
        for raw in f:
            line = raw.strip()
            if line.startswith("# Spec:") and spec is None:
                spec = line[len("# Spec:"):].strip()
                continue
            if line.startswith("Feature:"):
                title, in_feature = line[len("Feature:"):].strip() or title, True
                continue
            if in_feature:
                if line.startswith("@") or line.startswith("Scenario") or line.startswith("Example"):
                    break
                if line and not line.startswith("#"):
                    description.append(line)
    return title, description, spec


def relative(target, out_dir):
    return os.path.relpath(os.path.join(ROOT, target), out_dir).replace(os.sep, "/")


def label(scenario, level, game_tests, unit_tests):
    tags = scenario["tags"]
    if level == "pending":
        return "- [ ] **Pending:** checked by hand until its planned automated test exists"
    if level == "manual":
        return "- [ ] **Manual:** checked by hand for now"
    parts = []
    units = [t for t in tags if t in unit_tests]
    games = [t for t in tags if t in game_tests]
    if units:
        parts.append("unit " + ("tests " if len(units) > 1 else "test ") + ", ".join(f"`{t}`" for t in units))
    if games:
        parts.append("in game " + ", ".join(f"`{t}`" for t in games))
    return "**Automated:** " + "; ".join(parts)


def counts_row(counts):
    return " | ".join(str(counts[level]) for level in LEVELS) + f" | **{counts['manual'] + counts['pending']}**"


COUNTS_HEADER = "| Unit tests | Game tests | Manual | Pending | By hand |\n| --- | --- | --- | --- | --- |"


def feature_page(path, scenarios, game_tests, unit_tests, classify, out_dir):
    name = os.path.basename(path)
    source = f"tests/game/features/{name}"
    title, description, spec = feature_info(path)
    counts = dict.fromkeys(LEVELS, 0)
    body = []
    for scenario in scenarios:
        level = classify(scenario["tags"], game_tests, unit_tests)
        counts[level] += 1
        body += ["", f"### {scenario['title']}", "", label(scenario, level, game_tests, unit_tests), "", "```gherkin"]
        body += [f"    {step}" if step.startswith("|") else f"  {step}" for step in scenario["steps"]]
        body.append("```")
    links = f"Source: [`{source}`]({relative(source, out_dir)})"
    if spec:
        links += f" · Spec: [`{spec}`]({relative(spec, out_dir)})"
    lines = [HEADER.format(source=source), "", f"# {title}", ""]
    if description:
        lines += [" ".join(description), ""]
    lines += [links, "", COUNTS_HEADER, "| " + counts_row(counts) + " |", "", "## Scenarios"] + body
    return "\n".join(lines).rstrip() + "\n", title, counts


def index_page(rows, total):
    lines = [
        HEADER.format(source="tests/game/features/"),
        "",
        "# Test plan",
        "",
        "What the mod should do, feature by feature, and how each scenario is verified. Prefer the lowest "
        "level that can prove a scenario: unit tests, then game tests, then by hand. **By hand** (manual plus "
        "pending) is the number to drive to zero; see [`docs/PROJECT.md`](../PROJECT.md#workflow), \"Test plan\".",
        "",
        "| Feature | Scenarios | Unit tests | Game tests | Manual | Pending | By hand |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for page, title, counts in rows:
        lines.append(f"| [{title}]({page}) | {sum(counts.values())} | {counts_row(counts)} |")
    lines.append(f"| **Total** | {sum(total.values())} | {counts_row(total)} |")
    return "\n".join(lines) + "\n"


def generate(features_dir, harness, units_dir, out_dir):
    """Returns ({file name: content}, problems)."""
    checker = load_checker()
    scenarios, problems = checker.read_features(features_dir)
    if problems:
        return {}, problems
    game_tests = checker.game_test_names(harness)
    unit_tests, _ = checker.unit_test_names(units_dir)
    pages, rows, total = {}, [], dict.fromkeys(LEVELS, 0)
    for path in sorted(glob.glob(os.path.join(features_dir, "*.feature"))):
        name = os.path.basename(path)
        page = name[: -len(".feature")] + ".md"
        mine = [s for s in scenarios if s["file"] == name]
        content, title, counts = feature_page(path, mine, game_tests, unit_tests, checker.classify, out_dir)
        pages[page] = content
        rows.append((page, title, counts))
        for level in LEVELS:
            total[level] += counts[level]
    pages["README.md"] = index_page(rows, total)
    return pages, []


def main(argv):
    parser = argparse.ArgumentParser(description="Generate the readable test plan in docs/test-plan/.")
    parser.add_argument("--check", action="store_true", help="only check that the pages are up to date")
    parser.add_argument("--features", default=os.path.join(ROOT, "tests", "game", "features"))
    parser.add_argument("--harness", default=os.path.join(ROOT, "tests", "game", "apirateslife_tests", "md", "apirateslife_tests.xml"))
    parser.add_argument("--units", default=os.path.join(ROOT, "tests", "lua"))
    parser.add_argument("--out", default=os.path.join(ROOT, "docs", "test-plan"))
    args = parser.parse_args(argv)

    out_dir = os.path.abspath(args.out)
    pages, problems = generate(args.features, args.harness, args.units, out_dir)
    if problems:
        print("\n".join(problems), file=sys.stderr)
        print("Fix the test plan first (tools/check-test-plan.py)", file=sys.stderr)
        return 1

    existing = {os.path.basename(p) for p in glob.glob(os.path.join(out_dir, "*.md"))}
    stale = sorted(p for p, content in pages.items() if not _same(os.path.join(out_dir, p), content))
    extra = sorted(existing - set(pages))
    if args.check:
        if stale or extra:
            for page in stale:
                print(f"out of date: docs/test-plan/{page}")
            for page in extra:
                print(f"no feature file any more: docs/test-plan/{page}")
            print("Run make test-plan and commit the result")
            return 1
        print(f"Test-plan docs are up to date ({len(pages)} pages)")
        return 0

    os.makedirs(out_dir, exist_ok=True)
    for page in stale:
        with open(os.path.join(out_dir, page), "w", encoding="utf-8", newline="\n") as f:
            f.write(pages[page])
    for page in extra:
        os.remove(os.path.join(out_dir, page))
    changed = stale + extra
    print(f"Updated {len(changed)} of {len(pages)} test-plan pages" + (f": {', '.join(changed)}" if changed else ""))
    return 0


def _same(path, content):
    if not os.path.isfile(path):
        return False
    with open(path, encoding="utf-8") as f:
        return f.read() == content


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
